import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const base = new URL('../pages/simple-past/', import.meta.url);
const expected = `be|become|begin|bet|bite|blow up|break|bring|build|burn|buy|catch|choose|come|cost|creep|cut|do|draw|drink|drive|eat|fall|feed|feel|fight|find|fly|forget|get|give|go|hang up|have|hear|hide|hold up|hold|hurt|keep|know|lead|learn|leave|let|lie|light|lose|make|mean|meet|pay|put|read|ride|ring up|run|say|see|sell|send|set off|shoot off|show|sing|sit|sleep|smell|speak|spend|spoil|stand|steal|swim|take|tell|think|throw|understand|wake up|wear|win|write`.split('|');
const { VERBS, normalize, createSession, submit, retryMistakes } = await import(pathToFileURL(new URL('core.mjs', base).pathname));
const infinitives = VERBS.map(v => v.base);
assert.deepEqual(infinitives, expected, 'Only the verbs on photographed pages 292–293, in order');
assert.equal(new Set(infinitives).size, infinitives.length);
assert.ok(VERBS.every(v => v.past.length && v.german.length));
assert.deepEqual(VERBS.find(v => v.base === 'be').past, ['was', 'were']);
assert.deepEqual(VERBS.find(v => v.base === 'burn').past, ['burnt', 'burned']);
assert.deepEqual(VERBS.find(v => v.base === 'learn').past, ['learnt', 'learned']);
assert.deepEqual(VERBS.find(v => v.base === 'read').past, ['read']);
assert.deepEqual(VERBS.find(v => v.base === 'lie').past, ['lay']);
assert.deepEqual(VERBS.find(v => v.base === 'light').past, ['lit']);
assert.equal(normalize('  WROTE  '), 'wrote');
let session = createSession(VERBS.slice(0, 2));
assert.equal(submit(session, 'was').correct, true);
assert.equal(submit(session, 'become').correct, false);
assert.equal(session.errors[0].base, 'become');
assert.equal(session.errors[0].answer, 'become');
assert.equal(session.errors[0].expected, 'became');
assert.equal(session.index, 2);
assert.equal(submit(session, 'became').status, 'finished');
assert.equal(session.index, 2);
assert.equal(session.errors.length, 1);
session = retryMistakes(session);
assert.deepEqual(session.items.map(v => v.base), ['become']);
assert.equal(submit(session, 'became').correct, true);
assert.deepEqual(session.errors, []);
assert.equal(retryMistakes(session).items.length, 0);
const html = readFileSync(new URL('index.html', base), 'utf8');
const ui = readFileSync(new URL('app.mjs', base), 'utf8');
const short = readFileSync(new URL('../s/sp/index.html', base), 'utf8');
const catalog = readFileSync(new URL('../index.html', base), 'utf8');
assert.match(html, /assets\/qrcode-generator\.min\.js/);
assert.match(ui, /qrcode\(0, 'M'\)/);
assert.match(short, /\.\.\/\.\.\/simple-past\//);
assert.match(catalog, /data-share="s\/sp\/"/);
assert.doesNotMatch(ui, /fetch\(|sendBeacon|XMLHttpRequest|localStorage/);
console.log('simple past whitelist, errors, retry, QR and shortlink: OK');
