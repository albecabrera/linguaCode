import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const catalog = readFileSync(new URL('../pages/index.html', import.meta.url), 'utf8');
const cards = [...catalog.matchAll(/<article\b[^>]*data-subject="([^"]+)"[^>]*>([\s\S]*?)<\/article>/g)];
const matches = cards.filter(([, , body]) => body.includes('<h2>Blockprogrammierung mit Minecraft</h2>'));
assert.equal(matches.length, 1, 'Minecraft card appears exactly once');
const [, subject, card] = matches[0];
assert.equal(subject, 'Informatik');
assert.match(card, /Informatik · Klasse 7–10/);
assert.match(card, /href="minecraft-adventures\/"/);
assert.match(card, /data-share="s\/w\/"/);
assert.match(card, /[Oo]hne Anmeldung/);
const legacyShortlink = readFileSync(new URL('../pages/s/n/index.html', import.meta.url), 'utf8');
assert.match(legacyShortlink, /http-equiv="refresh" content="0; url=https:\/\/studio\.code\.org\/de\/courses\/aquatic\/units\/1\/lessons\/1\/levels\/1"/);
assert.match(legacyShortlink, /location\.replace\('https:\/\/studio\.code\.org\/de\/courses\/aquatic\/units\/1\/lessons\/1\/levels\/1'\)/);
const hubShortlink = readFileSync(new URL('../pages/s/w/index.html', import.meta.url), 'utf8');
assert.match(hubShortlink, /\.\.\/\.\.\/minecraft-adventures\//);
assert.ok(readFileSync(new URL('../pages/minecraft-adventures/index.html', import.meta.url), 'utf8').includes('<title>Minecraft Adventures · LinguaCode</title>'));
console.log('PASS: catalog hub entry, new /s/w/ shortlink, and preserved Aquatic Level 1 /s/n/ shortcut.');
