import assert from 'node:assert/strict';
import {VERBS, createQuest, answerQuest} from '../pages/simple-past/core.mjs';
import {createView, switchMode, moveStudy, requestTip, resetTip} from '../pages/simple-past/study.mjs';

const quest = createQuest();
const view = createView(quest);
assert.equal(view.mode, 'home');
assert.equal(view.studyIndex, 0);
assert.equal(view.quest, quest);
assert.equal(switchMode(view, 'study').mode, 'study');
assert.equal(moveStudy(view, 1), 1);
assert.equal(VERBS[view.studyIndex].base, 'become');
assert.equal(moveStudy(view, -1), 0);
assert.equal(moveStudy(view, -1), 0);
assert.equal(moveStudy(view, 100), VERBS.length - 1);
assert.equal(moveStudy(view, 1), VERBS.length - 1);
assert.equal(switchMode(view, 'game').mode, 'game');
assert.equal(view.quest, quest);
assert.equal(quest.round.index, 0, 'Study mode does not submit an answer');
assert.equal(requestTip(view, VERBS[0]), 'Beginnt mit w.');
assert.equal(requestTip(view, VERBS[0]), 'Die Form hat 3 Buchstaben.');
assert.equal(requestTip(view, VERBS[0]), 'Die Form hat 3 Buchstaben.');
assert.equal(quest.round.index, 0);
assert.equal(quest.streak, 0);
assert.equal(quest.rewardCount, 0);
assert.equal(answerQuest(quest, 'was').correct, true);
assert.equal(switchMode(view, 'study').mode, 'study');
assert.equal(switchMode(view, 'game').mode, 'game');
assert.equal(quest.round.index, 1, 'Switching modes preserves the active round');
resetTip(view);
assert.equal(requestTip(view, VERBS[1]), 'Beginnt mit b.');
assert.throws(() => switchMode(view, 'unknown'), /mode/i);
console.log('simple past study navigation, non-reset mode switching and non-scoring tips: OK');
