import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base = new URL('../pages/simple-past/', import.meta.url);
const html = readFileSync(new URL('index.html', base), 'utf8');
const css = readFileSync(new URL('style.css', base), 'utf8');
const app = readFileSync(new URL('app.mjs', base), 'utf8');
assert.match(html, /id="world"/);
assert.match(html, /id="sound-toggle"/);
assert.match(html, /id="cave"/);
assert.match(html, /id="dragon"/);
assert.match(html, /id="shortlink"/);
assert.match(app, /createQuest\(/);
assert.match(app, /answerQuest\(/);
assert.match(app, /advanceQuest\(/);
assert.match(html, /class="avatar"/);
assert.match(app, /avatar\.style\.setProperty\('--step'/);
assert.match(app, /role="status"/);
assert.match(app, /AudioContext|webkitAudioContext/);
assert.match(app, /oscillator|createOscillator/);
assert.match(app, /sound-toggle/);
assert.match(app, /result\.milestone/);
assert.match(app, /quest\.rewardCount/);
assert.match(app, /#streak-label/);
assert.match(app, /streak % 10/);
assert.match(css, /prefers-reduced-motion/);
assert.match(css, /focus-visible/);
assert.doesNotMatch(html + app + css, /https?:\/\/[^\s"']+\.(png|jpg|mp3|woff)/i, 'No borrowed artwork, sounds or fonts');
assert.doesNotMatch(app, /fetch\(|sendBeacon|XMLHttpRequest|localStorage/);
console.log('simple past block world UI, sound and privacy: OK');
